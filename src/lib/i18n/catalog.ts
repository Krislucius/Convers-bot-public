export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] == null ? `{${key}}` : String(vars[key]),
  );
}

export function t(key: string, locale: UiLanguage = DEFAULT_UI_LANGUAGE, vars?: Record<string, string | number>): string {
  const table = locale === "ru" ? RU : EN;
  const template = table[key] ?? EN[key] ?? key;
  return interpolate(template, vars);
}

export function statusLabel(status: string, locale: UiLanguage = DEFAULT_UI_LANGUAGE): string {
  const direct = locale === "ru" ? RU[`status.${status}`] : EN[`status.${status}`];
  if (direct) return direct;
  const verdict = locale === "ru" ? RU[`verdict.${status}`] : EN[`verdict.${status}`];
  if (verdict) return verdict;
  if (locale === "en") return status.replaceAll("_", " ");
  return EN[`status.${status}`] ?? status.replaceAll("_", " ");
}

export function actionLabel(action: string, locale: UiLanguage = DEFAULT_UI_LANGUAGE): string {
  return t(`action.${action}`, locale);
}

export function localizeErrorMessage(message: string, locale: UiLanguage = DEFAULT_UI_LANGUAGE): string {
  if (locale === "en") return message;
  const known = KNOWN_ENGLISH_ERRORS[message];
  if (known) return t(known, locale);
  const classKey = ERROR_CLASS_KEYS[message];
  if (classKey) return t(classKey, locale);
  return message;
}

export function localizeErrorClass(errorClass: string, locale: UiLanguage = DEFAULT_UI_LANGUAGE): string {
  const key = ERROR_CLASS_KEYS[errorClass];
  if (!key) return errorClass;
  return t(key, locale);
}

export function catalogParity(): { missingInRu: string[]; missingInEn: string[] } {
  const enKeys = Object.keys(EN);
  const ruKeys = Object.keys(RU);
  return {
    missingInRu: enKeys.filter((key) => !RU[key]),
    missingInEn: ruKeys.filter((key) => !EN[key]),
  };
}
